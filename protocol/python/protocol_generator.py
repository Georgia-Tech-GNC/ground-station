import json
from utils import *
from accessor_utils import *
import shutil

largest_sql_add_cmd_len = 0

FILEPATH_H = "../includes/protocol.h"
ALT_FILEPATH_H = "../../ground-station-core/lib/protocol/protocol.h"
FILEPATH_C = "../src/protocol.c"
ALT_FILEPATH_C = "../../ground-station-core/lib/protocol/protocol.c"
SQL_ENABLED_MACRO = "INCLUDE_PROTOCOL_SQL_MACROS"
WEB_SERVER_URL = "http://0.0.0.0:8080"
    
def generate_sql_add_cmd(name: str, content: dict[str, str]) -> str:
    global largest_sql_add_cmd_len

    sql_add_cmd = f"\"INSERT INTO {name} VALUES ({", ".join(["'" + cvt_type_to_str_fmt(i) + "'" for i in content.values()])}, '%s');\""
    length = len(f"\"INSERT INTO {name} VALUES ({", ".join(["'" + cvt_type_to_max_len_str(i) + "'" for i in content.values()])}, 'YYYY-MM-DD HH-MI-SS');\"")
    if length > largest_sql_add_cmd_len: 
        largest_sql_add_cmd_len = length
    return sql_add_cmd

def write_data_type(file, id: int, name: str, content: dict[str, str]):
    # Generate the struct
    file.write(f"struct {name} " + "{\n")
    for data_name, data_type in content.items():
        file.write(f"\t{data_type} {data_name};\n")
    file.write(f"\ttime_t timestamp;\n")
    file.write("};\n")

    # Define id
    file.write(f"#define {name.upper()}_MSG_ID {id}\n")

    # Define size
    file.write(f"#define {name.upper()}_SIZE sizeof(struct {name})\n")

    # Define number of values
    file.write(f"#define {name.upper()}_NUM_VALUES {len(content) + 1}\n")

    # Start SQL section
    file.write(f"#ifdef {SQL_ENABLED_MACRO}\n")

    # Generate the SQL Table
    file.write(f"\t#define {name.upper()}_SQL_TABLE_GEN \"CREATE TABLE {name} ( \" \\\n")
    for data_name, data_type in content.items():    
        file.write(f"\t\t\"{data_name} {cvt_type_to_sql(data_type)},\" \\\n")
    file.write("\t\t\"time datetime PRIMARY KEY);\"\n")

    # SQL Query Command
    file.write(f"\t#define {name.upper()}_SQL_GET_MOST_RECENT \"SELECT TOP 1 " + 
               ", ".join([data_name for data_name in content.keys()] + ["time"]) + " " +
               f"FROM {name} ORDER BY time\"\n")

    # SQL Add command
    sql_add_cmd = generate_sql_add_cmd(name, content)
    file.write(f"\t#define {name.upper()}_SQL_ADD_ENTRY(buffer, data, timestamp) sprintf(buffer, \\\n\t\t{sql_add_cmd}, \\\n\t\t{", \\\n\t\t".join(["data->" + i for i in content.keys()])}, \\\n\t\ttimestamp); \n")

    # Web API Path
    file.write(f"\t#define {name.upper()}_API_PATH WEB_SERVER_URL \"/api/data/{name}\"\n")

    # SQL TO JSON ENCODE
    file.write(f"\t#define {name.upper()}_SQL_SELECT_TO_JSON(sql_row_values) " + 
                "\"{ " + ", ".join(["%m: %s" for _ in range(len(content)+1)]) + " }\", \\\n" +
                " \\\n".join([f"\t\t\tMG_ESC(\"{data_name}\"), sql_row_values[{i}]," for i, data_name in enumerate(content.keys())]) + 
                f" \\\n\t\t\tMG_ESC(\"timestamp\"), sql_row_values[{len(content)}]\n"
    )

    # End SQL section
    file.write("#endif\n\n")

def generate_asterisk_comment(num_lines: int, num_ast: int):
    return "\n".join(["//"+("*"*num_ast) for _ in range(num_lines)]) + "\n"

def main():
    global largest_sql_add_cmd_len
    largest_sql_add_cmd_len = 0

    d = {}
    with open('protocol.json') as f:
        d = json.load(f)

    id_counter = 2
    max_data_message_id = 1

    with open(FILEPATH_H, 'w') as file:
        file.write("#ifndef PROTOCOL_H\n#define PROTOCOL_H\n\n#include <time.h>\n#include <stdbool.h>\n#include <stdint.h>\n#include <stdio.h>\n\n")

        file.write(f"// Uncomment this line to include SQL macros\n//#define {SQL_ENABLED_MACRO}\n\n")

        file.write(generate_asterisk_comment(3, 100))
        file.write('// DISCLAIMER: THIS FILE WAS AUTO-GENERATED BY protocol_generator.py\n')
        file.write('// DO NOT MODIFY THIS FILE DIRECTLY!\n')
        file.write('// TO MODIFY THE PROTOCOL, EDIT protocol.json AND RE-RUN protocol_generator.py\n')
        file.write(generate_asterisk_comment(3, 100))
        file.write('\n\n')

        # Write the header for converting longs to SQL timestamps
        file.write("#ifdef INCLUDE_PROTOCOL_SQL_MACROS\n" +
                   "\tvoid generate_sql_timestamp_from_long(time_t time, char* buffer);\n" +
                   f"\t#define WEB_SERVER_URL \"{WEB_SERVER_URL}\"\n#endif\n\n")
        
        # Write the max sql value size
        file.write("#define MAX_SQL_VAL_SIZE 30\n\n")

        # Write all data types
        for name, content in d["data_types"].items():
            write_data_type(file, id_counter, name, content)
            id_counter += 1
        max_data_message_id = id_counter - 1

        # Write the get message size method
        file.write(generate_get_msg_len_header())

        # Write the is message a data message method
        file.write(generate_get_is_data_msg_header())

        # Enter SQL Mode
        file.write(f"#ifdef {SQL_ENABLED_MACRO}\n")

        # Write the maximum SQL add command size
        file.write(f"\t#define MAX_SQL_WRITE_CMD_SIZE {largest_sql_add_cmd_len+11}\n\n")

        # Write the array of all SQL create commands
        file.write(f"\t#define ALL_SQL_TABLE_CREATE_COMMANDS " + ", ".join([i.upper() + "_SQL_TABLE_GEN" for i in d["data_types"].keys()]) + "\n\n")
        file.write(f"\t#define NUM_SQL_TABLES {len(d["data_types"])}\n\n")

        # Write the array of all data API commands
        file.write(f"\t#define ALL_API_DATA_PATHS " + ", ".join([i.upper() + "_API_PATH" for i in d['data_types'].keys()]) + "\n\n")

        # Write the convert data to sql method
        file.write(generate_cvt_packet_to_sql_header())

        # Write API if else
        file.write("\t#define HANDLE_API_INPUT(db, hm) " + generate_api_if_else(d['data_types'].keys()) + "\n\n")

        # Exit SQL Mode
        file.write("#endif\n\n")

        # End the file
        file.write("#endif")
        
    with open(FILEPATH_C, 'w') as file:
        file.write("#include \"protocol.h\"\n#include <time.h>\n#include <stdbool.h>\n#include <stdint.h>\n#include <stdio.h>\n\n")

        file.write(generate_asterisk_comment(3, 100))
        file.write('// DISCLAIMER: THIS FILE WAS AUTO-GENERATED BY protocol_generator.py\n')
        file.write('// DO NOT MODIFY THIS FILE DIRECTLY!\n')
        file.write('// TO MODIFY THE PROTOCOL, EDIT protocol.json AND RE-RUN protocol_generator.py\n')
        file.write(generate_asterisk_comment(3, 100))
        file.write('\n\n')

        # Write the get message size method
        file.write(generate_get_msg_len(d["data_types"].keys()))

        # Write the is message a data message method
        file.write(generate_get_is_data_msg(max_data_message_id))

        # Enter SQL Mode
        file.write(f"#ifdef {SQL_ENABLED_MACRO}\n")

        # Write the convert data to sql method
        file.write(generate_cvt_to_sql_time())
        file.write(generate_cvt_packet_to_sql(d["data_types"].keys()))

        # Exit SQL Mode
        file.write("#endif\n\n")

    # Copy files
    shutil.copyfile(FILEPATH_H, ALT_FILEPATH_H)
    shutil.copyfile(FILEPATH_C, ALT_FILEPATH_C)


if __name__ == "__main__":
    main()